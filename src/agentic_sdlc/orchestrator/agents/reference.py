def _architecture_doc(context: AgentContext, ambiguous: bool) -> str:
    analytics = (
        "Click events feed aggregate endpoints; raw IPs are never stored, only salted hashes."
        if ambiguous
        else "Click events are appended transactionally with a denormalized counter."
    )
    return f"""# Architecture

## Context

{context.requirement.strip()[:500]}

## Components

| Component | Responsibility |
|---|---|
| API layer | Request validation, auth, rate limiting, HTTP semantics |
| Shortener service | Code allocation, TTL/idempotency rules, redirect orchestration |
| Repository | Transactional persistence, analytics aggregation |
| Orchestration control plane | DAG scheduling, gates, approvals, audit, metrics |
| Dashboard | Operator visibility and approval inbox |

## Control flow

```mermaid
flowchart LR
  C[Client] -->|POST /api/v1/links| A[API]
  A --> V[URL validator]
  V --> S[Shortener service]
  S --> R[(SQLite)]
  C -->|GET /{{code}}| D[Redirect]
  D --> R
  D --> E[Click event]
  E --> R
  A -.audit.-> L[(Audit chain)]
```

## API surface

- `POST /api/v1/links` — create (Idempotency-Key supported)
- `GET /api/v1/links/{{code}}` — metadata
- `DELETE /api/v1/links/{{code}}` — soft delete
- `GET /api/v1/links/{{code}}/analytics` — aggregates
- `GET /{{code}}` — 302 redirect
- `GET /healthz`, `/readyz`, `/metrics`

## Data model

`links(id, code, target_url, created_at, expires_at, deleted_at, idempotency_key, click_count)`
and `click_events(id, link_id, code, clicked_at, referrer, user_agent, visitor_hash, country)`.
Indexes support `(link_id, clicked_at)` and `(code, clicked_at)`.

## Security controls

- Scheme allowlist: only `http` and `https`; `javascript:`, `file:` and credential-bearing URLs
  are rejected.
- SSRF hardening: reject loopback, private, link-local, reserved and multicast destinations,
  including integer/hex IPv4 representations and metadata endpoints.
- The redirect path performs no server-side fetch, so the residual SSRF surface is limited to
  clients following the redirect; a production egress proxy provides defense in depth.
- Redirect responses set `Cache-Control: no-store` and `X-Robots-Tag: noindex` to reduce
  cache poisoning and indexing abuse.
- API keys gate management routes; analytics identifiers are salted hashes.

## Reliability

{analytics} TTL is evaluated at read time. Idempotency is enforced by a unique key. WAL mode
plus `BEGIN IMMEDIATE` serializes writers without blocking readers. Rate limiting uses a token
bucket keyed by API key or client address.

## Trade-offs

- SQLite keeps the prototype zero-infra; Postgres is the production target.
- Analytics are computed on demand; pre-aggregation is a scale follow-up.
- Soft delete preserves auditability at the cost of retention management.
"""


