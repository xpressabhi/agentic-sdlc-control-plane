EXTENSION_MODULE = textwrap.dedent(
    '''
    """Brownfield extension generated by the implementation agent.

    Adds custom-alias normalization, TTL helpers and analytics aggregation on top
    of the existing Base62 core. Secrets are read from the environment; never
    commit credentials.
    """
    from __future__ import annotations

    import os
    import re

    ANALYTICS_RETENTION_DAYS = 90
    ALIAS_PATTERN = re.compile(r"^[a-z0-9](?:[a-z0-9_-]{1,30}[a-z0-9])$")


    def normalize_alias(alias: str) -> str:
        alias = alias.strip().lower()
        if not ALIAS_PATTERN.match(alias):
            raise ValueError("alias must be 3-32 lowercase characters")
        return alias


    def expiry_from_ttl(now_epoch: int, ttl_seconds: int | None) -> int | None:
        if ttl_seconds is None:
            return None
        if ttl_seconds < 30 or ttl_seconds > 31_536_000:
            raise ValueError("ttl out of bounds")
        return now_epoch + ttl_seconds


    def aggregate_daily(events: list[dict]) -> list[dict]:
        buckets: dict[str, int] = {}
        for event in events:
            day = str(event["clicked_at"])[:10]
            buckets[day] = buckets.get(day, 0) + 1
        return [{"day": day, "clicks": buckets[day]} for day in sorted(buckets)]


    def top_referrers(events: list[dict], limit: int = 10) -> list[dict]:
        counts: dict[str, int] = {}
        for event in events:
            referrer = event.get("referrer") or "direct"
            counts[referrer] = counts.get(referrer, 0) + 1
        ranked = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
        return [{"referrer": key, "clicks": value} for key, value in ranked[:limit]]


    def analytics_salt() -> str:
        value = os.environ.get("ANALYTICS_SALT")
        if not value:
            raise RuntimeError("ANALYTICS_SALT must be configured")
        return value
    '''
).strip()

