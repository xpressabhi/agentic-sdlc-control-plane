class ValidationAgent:
    name = "validation"

    def execute(self, context: AgentContext) -> AgentResult:
        artifacts: list[ArtifactDraft] = []
        sources: dict[str, ArtifactDraft] = {}
        for records in context.upstream.values():
            for record in records:
                if record.name.endswith(".py"):
                    sources[Path(record.name).name] = ArtifactDraft(
                        record.name, record.kind, record.content
                    )
        tests = [name for name in sources if Path(name).name.startswith("test_")]
        workspace = Path(context.workspace) / "validation" / f"attempt-{context.attempt}"
        workspace.mkdir(parents=True, exist_ok=True)
        for name, draft in sources.items():
            (workspace / Path(name).name).write_text(draft.content)

        if not tests:
            return AgentResult(
                summary="No executable tests found upstream",
                success=False,
                retryable=False,
                error="validation requires at least one generated test artifact",
            )

        logs: list[str] = []
        passed = True
        for test in sorted(tests):
            try:
                proc = subprocess.run(
                    [sys.executable, Path(test).name],
                    cwd=workspace,
                    capture_output=True,
                    text=True,
                    timeout=30,
                    check=False,
                )
                logs.append(
                    f"$ python {test}\nexit={proc.returncode}\n"
                    f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
                )
                passed = passed and proc.returncode == 0
            except subprocess.TimeoutExpired:
                logs.append(f"$ python {test}\nTIMEOUT after 30s")
                passed = False
        report = "# Validation Report\n\n"
        report += f"- Tests executed: {len(tests)}\n"
        report += f"- Result: {'PASSED' if passed else 'FAILED'}\n"
        report += "- Evidence: captured stdout/stderr in `validation-log.txt`\n"
        artifacts.append(
            ArtifactDraft(
                "test-report.md",
                "report",
                report,
                metadata={"tests_passed": passed, "test_count": len(tests)},
            )
        )
        artifacts.append(ArtifactDraft("validation-log.txt", "log", "\n\n".join(logs)))
        return AgentResult(
            summary=f"Executed {len(tests)} generated test file(s): "
            f"{'PASSED' if passed else 'FAILED'}",
            artifacts=artifacts,
            decisions=[
                DecisionDraft(
                    "validation.evidence",
                    "Generated tests executed in an isolated workspace",
                    f"{len(tests)} test file(s), result={'PASSED' if passed else 'FAILED'}",
                )
            ],
            metadata={"tests_passed": passed, "test_count": len(tests)},
            success=passed,
            retryable=True,
            error=None if passed else "generated tests failed",
        )


