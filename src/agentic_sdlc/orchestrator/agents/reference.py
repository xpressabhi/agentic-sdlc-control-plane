class MigrationAgent:
    name = "migration"

    def execute(self, context: AgentContext) -> AgentResult:
        with tempfile.TemporaryDirectory() as tmp:
            db_path = Path(tmp) / "sandbox.db"
            conn = sqlite3.connect(db_path)
            try:
                conn.executescript(
                    """
                    CREATE TABLE links (
                        id INTEGER PRIMARY KEY,
                        code TEXT NOT NULL UNIQUE,
                        target_url TEXT NOT NULL,
                        created_at TEXT NOT NULL,
                        click_count INTEGER NOT NULL DEFAULT 0
                    );
                    INSERT INTO links (code, target_url, created_at)
                    VALUES ('seed001', 'https://example.com', '2026-01-01T00:00:00Z');
                    """
                )
                conn.executescript(MIGRATION_SQL)
                columns = {row[1] for row in conn.execute("PRAGMA table_info(links)")}
                tables = {
                    row[0]
                    for row in conn.execute(
                        "SELECT name FROM sqlite_master WHERE type='table'"
                    )
                }
                assert {"expires_at", "deleted_at", "metadata_json"} <= columns
                assert "click_events" in tables
                count = conn.execute("SELECT COUNT(*) FROM links").fetchone()[0]
                assert count == 1
                report = (
                    "Migration verified in sandbox.\n"
                    f"columns={sorted(columns)}\ntables={sorted(tables)}\n"
                    f"preserved_rows={count}"
                )
            finally:
                conn.close()
        return AgentResult(
            summary="Migration authored and applied to a sandbox database",
            artifacts=[
                ArtifactDraft("migrations/002_aliases_analytics_ttl.sql", "sql", MIGRATION_SQL),
                ArtifactDraft("migration-verification.txt", "log", report),
            ],
            decisions=[
                DecisionDraft(
                    "migration.strategy",
                    "Additive migration with nullable columns and new table",
                    "Preserves existing rows and supports rollback without data loss",
                )
            ],
            metadata={"migration_verified": True},
        )


