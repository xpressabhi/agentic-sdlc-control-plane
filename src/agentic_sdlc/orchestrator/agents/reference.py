GENERATED_CORE = textwrap.dedent(
    '''
    """URL-shortener core generated by the implementation agent.

    This module is intentionally dependency-free so the validation stage can
    execute it in an isolated workspace.
    """
    from __future__ import annotations

    import ipaddress
    import re
    from urllib.parse import urlsplit

    ALPHABET = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
    BASE = len(ALPHABET)
    ALIAS_PATTERN = re.compile(r"^[A-Za-z0-9_-]{3,32}$")
    RESERVED = {"api", "healthz", "readyz", "metrics", "dashboard", "static"}


    class InvalidURL(ValueError):
        pass


    class InvalidAlias(ValueError):
        pass


    def encode(number: int) -> str:
        if number < 0:
            raise ValueError("number must be non-negative")
        if number == 0:
            return ALPHABET[0]
        digits = []
        while number:
            number, remainder = divmod(number, BASE)
            digits.append(ALPHABET[remainder])
        return "".join(reversed(digits))


    def decode(code: str) -> int:
        value = 0
        for char in code:
            index = ALPHABET.find(char)
            if index < 0:
                raise ValueError(f"invalid character: {char!r}")
            value = value * BASE + index
        return value


    def generate_code(length: int = 7) -> str:
        import secrets
        if length < 3:
            raise ValueError("length must be at least 3")
        return "".join(secrets.choice(ALPHABET) for _ in range(length))


    def validate_alias(alias: str) -> str:
        alias = alias.strip()
        if not ALIAS_PATTERN.match(alias):
            raise InvalidAlias("alias must be 3-32 alphanumeric, '-' or '_' characters")
        if alias.lower() in RESERVED:
            raise InvalidAlias("alias is reserved")
        return alias


    def _parse_ip(host: str):
        try:
            return ipaddress.ip_address(host)
        except ValueError:
            pass
        if host.isdigit():
            try:
                return ipaddress.IPv4Address(int(host))
            except (ValueError, OverflowError):
                return None
        if host.lower().startswith("0x"):
            try:
                return ipaddress.IPv4Address(int(host, 16))
            except (ValueError, OverflowError):
                return None
        return None


    def validate_url(raw: str, max_length: int = 2048) -> str:
        url = raw.strip()
        if not url:
            raise InvalidURL("url must not be empty")
        if len(url) > max_length:
            raise InvalidURL("url is too long")
        parsed = urlsplit(url)
        if parsed.scheme.lower() not in {"http", "https"}:
            raise InvalidURL("only http and https are allowed")
        if not parsed.hostname:
            raise InvalidURL("hostname is required")
        if parsed.username or parsed.password:
            raise InvalidURL("credentials are not allowed")
        host = parsed.hostname.lower().rstrip(".")
        if host in {"localhost", "metadata.google.internal"} or host.endswith(
            (".localhost", ".local", ".internal")
        ):
            raise InvalidURL("private destinations are not allowed")
        ip = _parse_ip(host)
        if ip is not None and (
            ip.is_private
            or ip.is_loopback
            or ip.is_link_local
            or ip.is_reserved
            or ip.is_multicast
            or ip.is_unspecified
        ):
            raise InvalidURL("private destinations are not allowed")
        try:
            port = parsed.port
        except ValueError as exc:
            raise InvalidURL("invalid port") from exc
        netloc = host if port is None else f"{host}:{port}"
        from urllib.parse import urlunsplit
        return urlunsplit((parsed.scheme.lower(), netloc, parsed.path or "/", parsed.query, ""))


    def is_expired(expires_at: str | None, now: str) -> bool:
        return expires_at is not None and expires_at <= now
    '''
).strip()

